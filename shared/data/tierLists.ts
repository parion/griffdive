import type { Tier } from './types'

// Featured tier lists shipped with the app: playable offline, versioned with
// the app, credited like any other community contribution. Each preset is a
// whole list in its own right, written out tier by tier — never computed from
// the default tiers, so a catalog refresh can't quietly change one. Submit a
// list by pull request (its JSON export pastes straight in) and add its
// author to CREDITS. An item a preset doesn't name plays at its catalog tier.
export interface TierListPreset {
  id: string
  name: string
  blurb: string
  credit: string
  tiers: Readonly<Record<Tier, readonly string[]>>
}

